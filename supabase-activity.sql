create table if not exist public.aktifitas_fieldtrip (
    id bigint generated by default as identity primary key,
    nama_kegiatan text not null check (char_length(trim(nama_kegiatan)) between 1 and 255),
    tanggal_kegiatan date not null,
    created_at timestamptz not null default now(),
    updated_at timestamptz not null default now()
);

create table if not exist public.aktifitas_fieldtrip_photo (
    id bigint generated by default as identity primary key,
    aktifitas_fieldtrip_id bigint not null references public.aktifitas_fieldtrip (id) on delete restrict,
    url_foto text not null,
    created_at timestamptz not null default now(),
    updated_at timestamptz not null default now(),
    foreign key (aktifitas_fieldtrip_id)
      references public.aktifitas_fieldtrip (id) on delete restrict,
    unique (aktifitas_fieldtrip_id, url_foto)
);

