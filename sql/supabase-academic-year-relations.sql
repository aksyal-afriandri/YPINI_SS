-- Run supabase-schema.sql and supabase-academic-year-settings.sql first.
-- Select the current academic year in the admin UI before running this migration
-- so existing classes and student links can be copied into that year.

create table if not exists public.kelas_tahun_ajaran (
  id bigint generated by default as identity primary key,
  kelas_id bigint not null references public.data_kelas (id) on delete restrict,
  tahun_ajaran_id bigint not null references public.tahun_ajaran (id) on delete restrict,
  jenjang text not null default 'Belum ditentukan',
  nama_kelas text not null check (char_length(trim(nama_kelas)) between 1 and 255),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (kelas_id, tahun_ajaran_id),
  unique (id, tahun_ajaran_id)
);

alter table public.kelas_tahun_ajaran
  add column if not exists jenjang text not null default 'Belum ditentukan';

do $$
begin
  if not exists (
    select 1 from pg_constraint
    where conname = 'kelas_tahun_ajaran_jenjang_check'
      and conrelid = 'public.kelas_tahun_ajaran'::regclass
  ) then
    alter table public.kelas_tahun_ajaran
      add constraint kelas_tahun_ajaran_jenjang_check
      check (char_length(trim(jenjang)) between 1 and 30);
  end if;
end;
$$;

create table if not exists public.siswa_kelas_tahun_ajaran (
  id bigint generated by default as identity primary key,
  siswa_id bigint not null references public.data_siswa (id) on delete cascade,
  kelas_tahun_ajaran_id bigint not null,
  tahun_ajaran_id bigint not null references public.tahun_ajaran (id) on delete restrict,
  tanggal_mulai date not null default current_date,
  tanggal_selesai date,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  foreign key (kelas_tahun_ajaran_id, tahun_ajaran_id)
    references public.kelas_tahun_ajaran (id, tahun_ajaran_id) on delete restrict,
  check (tanggal_selesai is null or tanggal_selesai >= tanggal_mulai),
  unique (siswa_id, kelas_tahun_ajaran_id, tanggal_mulai)
);

alter table public.absensi
  add column if not exists siswa_kelas_tahun_ajaran_id bigint
  references public.siswa_kelas_tahun_ajaran (id) on delete restrict;

alter table public.wali_kelas
  add column if not exists kelas_tahun_ajaran_id bigint
  references public.kelas_tahun_ajaran (id) on delete set null;

create index if not exists siswa_kelas_tahun_ajaran_year_class_idx
  on public.siswa_kelas_tahun_ajaran (tahun_ajaran_id, kelas_tahun_ajaran_id);
create index if not exists siswa_kelas_tahun_ajaran_student_year_dates_idx
  on public.siswa_kelas_tahun_ajaran (siswa_id, tahun_ajaran_id, tanggal_mulai, tanggal_selesai);
create index if not exists absensi_placement_date_idx
  on public.absensi (siswa_kelas_tahun_ajaran_id, tanggal);
create or replace function public.sync_wali_kelas_academic_year()
returns trigger
language plpgsql
set search_path = ''
as $$
begin
  if new.kelas_tahun_ajaran_id is not null then
    select kelas_id, tahun_ajaran_id
      into new.kelas_id, new.tahun_ajaran_id
      from public.kelas_tahun_ajaran
      where id = new.kelas_tahun_ajaran_id;
  end if;
  return new;
end;
$$;

drop trigger if exists wali_kelas_sync_academic_year on public.wali_kelas;
create trigger wali_kelas_sync_academic_year before insert or update on public.wali_kelas
  for each row execute procedure public.sync_wali_kelas_academic_year();

drop trigger if exists kelas_tahun_ajaran_set_updated_at on public.kelas_tahun_ajaran;
create trigger kelas_tahun_ajaran_set_updated_at before update on public.kelas_tahun_ajaran
  for each row execute procedure public.set_updated_at();
drop trigger if exists siswa_kelas_tahun_ajaran_set_updated_at on public.siswa_kelas_tahun_ajaran;
create trigger siswa_kelas_tahun_ajaran_set_updated_at before update on public.siswa_kelas_tahun_ajaran
  for each row execute procedure public.set_updated_at();

grant select, insert, update, delete on public.kelas_tahun_ajaran to authenticated;
grant select, insert, update, delete on public.siswa_kelas_tahun_ajaran to authenticated;
grant select, update on public.absensi to authenticated;
grant select, insert, update, delete on public.wali_kelas to authenticated;
grant usage, select on all sequences in schema public to authenticated;

alter table public.kelas_tahun_ajaran enable row level security;
alter table public.siswa_kelas_tahun_ajaran enable row level security;

drop policy if exists kelas_tahun_ajaran_admin_all on public.kelas_tahun_ajaran;
create policy kelas_tahun_ajaran_admin_all on public.kelas_tahun_ajaran for all to authenticated
  using ((select public.is_admin())) with check ((select public.is_admin()));
drop policy if exists siswa_kelas_tahun_ajaran_admin_all on public.siswa_kelas_tahun_ajaran;
create policy siswa_kelas_tahun_ajaran_admin_all on public.siswa_kelas_tahun_ajaran for all to authenticated
  using ((select public.is_admin())) with check ((select public.is_admin()));

-- Existing attendance has no reliable academic-year/class reference; keep it intact
-- and leave the new nullable relation empty rather than guessing its history.
insert into public.kelas_tahun_ajaran (kelas_id, tahun_ajaran_id, nama_kelas)
select k.id, setting.tahun_ajaran_id, k.nama_kelas
from public.data_kelas k
cross join public.pengaturan_tahun_ajaran setting
where setting.id = 1
on conflict (kelas_id, tahun_ajaran_id) do nothing;

insert into public.kelas_tahun_ajaran (kelas_id, tahun_ajaran_id, nama_kelas)
select distinct kelas.id, wali.tahun_ajaran_id, kelas.nama_kelas
from public.wali_kelas wali
join public.data_kelas kelas on kelas.id = wali.kelas_id
on conflict (kelas_id, tahun_ajaran_id) do nothing;

insert into public.siswa_kelas_tahun_ajaran (
  siswa_id, kelas_tahun_ajaran_id, tahun_ajaran_id, tanggal_mulai
)
select old_link.siswa_id, class_year.id, class_year.tahun_ajaran_id, current_date
from public.siswa_kelas old_link
join public.kelas_tahun_ajaran class_year on class_year.kelas_id = old_link.kelas_id
join public.pengaturan_tahun_ajaran setting
  on setting.tahun_ajaran_id = class_year.tahun_ajaran_id and setting.id = 1
where not exists (
  select 1
  from public.siswa_kelas_tahun_ajaran existing
  where existing.siswa_id = old_link.siswa_id
    and existing.kelas_tahun_ajaran_id = class_year.id
    and existing.tahun_ajaran_id = class_year.tahun_ajaran_id
)
on conflict (siswa_id, kelas_tahun_ajaran_id, tanggal_mulai) do nothing;

update public.wali_kelas wali
set kelas_tahun_ajaran_id = class_year.id
from public.kelas_tahun_ajaran class_year
where class_year.kelas_id = wali.kelas_id
  and class_year.tahun_ajaran_id = wali.tahun_ajaran_id
  and wali.kelas_tahun_ajaran_id is null;
