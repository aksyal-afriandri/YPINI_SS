-- 3. TABEL UJIAN (PENGATURAN UJIAN)
CREATE TABLE IF NOT EXISTS public.ujian (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nama_ujian text NOT NULL CHECK (char_length(trim(nama_ujian)) BETWEEN 1 AND 255),
  pelajaran_id bigint NOT NULL REFERENCES public.data_pelajaran (id) ON DELETE RESTRICT,
  waktu_menit integer NOT NULL CHECK (waktu_menit > 0),
  dibuka_at timestamptz NOT NULL,
  ditutup_at timestamptz NOT NULL,
  acak_soal boolean NOT NULL DEFAULT false,
  acak_jawaban boolean NOT NULL DEFAULT false,
  aktif boolean NOT NULL DEFAULT false,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  CHECK (dibuka_at < ditutup_at)
);

-- 4. TABEL SOAL UJIAN (MENDUKUNG FOTO & MULTI-FOTO)
CREATE TABLE IF NOT EXISTS public.soal_ujian (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  ujian_id bigint NOT NULL REFERENCES public.ujian (id) ON DELETE CASCADE,
  nomor_urut integer NOT NULL CHECK (nomor_urut > 0),
  soal_type public.soal_type NOT NULL,
  pertanyaan text NOT NULL CHECK (char_length(trim(pertanyaan)) > 0),
  pilihan_a text,
  pilihan_b text,
  pilihan_c text,
  pilihan_d text,
  gambar_url text,
  gambar_urls text[],
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  UNIQUE (ujian_id, nomor_urut),
  UNIQUE (id, ujian_id),
  CHECK (
    (soal_type = 'pg' AND pilihan_a IS NOT NULL AND pilihan_b IS NOT NULL
      AND pilihan_c IS NOT NULL AND pilihan_d IS NOT NULL)
    OR
    (soal_type = 'essay' AND pilihan_a IS NULL AND pilihan_b IS NULL
      AND pilihan_c IS NULL AND pilihan_d IS NULL)
  )
);

-- Pastikan kolom gambar_url dan gambar_urls ada jika tabel sudah pernah dibuat sebelumnya
ALTER TABLE public.soal_ujian ADD COLUMN IF NOT EXISTS gambar_url text;
ALTER TABLE public.soal_ujian ADD COLUMN IF NOT EXISTS gambar_urls text[];
ALTER TABLE public.soal_ujian DROP COLUMN IF EXISTS nilai_maksimum;

-- 5. TABEL KUNCI PILIHAN GANDA
CREATE TABLE IF NOT EXISTS public.kunci_pg (
  soal_id bigint PRIMARY KEY REFERENCES public.soal_ujian (id) ON DELETE CASCADE,
  jawaban_benar char(1) NOT NULL CHECK (jawaban_benar IN ('A', 'B', 'C', 'D'))
);

-- 6. TABEL JAWABAN ACUAN ESSAY
CREATE TABLE IF NOT EXISTS public.jawaban_acuan_essay (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  soal_id bigint NOT NULL REFERENCES public.soal_ujian (id) ON DELETE CASCADE,
  jawaban text NOT NULL CHECK (char_length(trim(jawaban)) > 0),
  UNIQUE (soal_id, jawaban)
);

-- 7. TABEL PERCOBAAN UJIAN (HASIL / STATUS PENGERJAAN SISWA)
CREATE TABLE IF NOT EXISTS public.percobaan_ujian (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  ujian_id bigint NOT NULL REFERENCES public.ujian (id) ON DELETE CASCADE,
  siswa_id bigint NOT NULL REFERENCES public.data_siswa (id) ON DELETE CASCADE,
  status text NOT NULL DEFAULT 'berlangsung'
    CHECK (status IN ('berlangsung', 'dikumpulkan', 'dinilai')),
  mulai_at timestamptz NOT NULL DEFAULT now(),
  dikumpulkan_at timestamptz,
  nilai_pilihan_ganda numeric(8, 2) CHECK (nilai_pilihan_ganda >= 0),
  nilai_essay_final numeric(8, 2) CHECK (nilai_essay_final >= 0),
  nilai_total numeric(8, 2) CHECK (nilai_total >= 0),
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  UNIQUE (id, ujian_id)
);

-- 8. TABEL JAWABAN SISWA
CREATE TABLE IF NOT EXISTS public.jawaban_siswa (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  percobaan_id bigint NOT NULL,
  ujian_id bigint NOT NULL,
  soal_id bigint NOT NULL,
  urutan_soal integer NOT NULL CHECK (urutan_soal > 0),
  urutan_opsi_tampil text[],
  jawaban_pg char(1) CHECK (jawaban_pg IN ('A', 'B', 'C', 'D')),
  jawaban_essay text,
  nilai_otomatis numeric(8, 2) CHECK (nilai_otomatis >= 0),
  status_ai text CHECK (status_ai IN ('menunggu', 'cocok', 'perlu_tinjau', 'tidak_cocok', 'gagal')),
  nilai_ai numeric(8, 2) CHECK (nilai_ai >= 0),
  catatan_ai text,
  nilai_final numeric(8, 2) CHECK (nilai_final >= 0),
  catatan_guru text,
  ditinjau_oleh uuid REFERENCES public.profiles (user_id) ON DELETE SET NULL,
  ditinjau_at timestamptz,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  FOREIGN KEY (percobaan_id, ujian_id)
    REFERENCES public.percobaan_ujian (id, ujian_id) ON DELETE CASCADE,
  FOREIGN KEY (soal_id, ujian_id)
    REFERENCES public.soal_ujian (id, ujian_id) ON DELETE CASCADE,
  UNIQUE (percobaan_id, soal_id),
  UNIQUE (percobaan_id, urutan_soal),
  CHECK (jawaban_pg IS NULL OR jawaban_essay IS NULL),
  CHECK (urutan_opsi_tampil IS NULL OR cardinality(urutan_opsi_tampil) = 4)
);

