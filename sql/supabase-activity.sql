-- ------------------------------------------------------------------------------
-- 6. MIGRATION & ADAPTASI TABEL JIKA SUDAH PERNAH DIBUAT SEBELUMNYA
-- ------------------------------------------------------------------------------
do $$
begin
  -- Tambah kolom deskripsi jika belum ada
  if not exists (select 1 from information_schema.columns where table_schema='public' and table_name='aktifitas_fieldtrip' and column_name='deskripsi') then
    alter table public.aktifitas_fieldtrip add column deskripsi text;
  end if;
  if not exists (select 1 from information_schema.columns where table_schema='public' and table_name='aktifitas_akhwah' and column_name='deskripsi') then
    alter table public.aktifitas_akhwah add column deskripsi text;
  end if;
  if not exists (select 1 from information_schema.columns where table_schema='public' and table_name='aktifitas_ummi' and column_name='deskripsi') then
    alter table public.aktifitas_ummi add column deskripsi text;
  end if;
  if not exists (select 1 from information_schema.columns where table_schema='public' and table_name='aktifitas_pembelajaran' and column_name='deskripsi') then
    alter table public.aktifitas_pembelajaran add column deskripsi text;
  end if;

  -- Rename kolom foreign key lama (jika ada aktifitas_fieldtrip_id -> aktifitas_id)
  if exists (select 1 from information_schema.columns where table_schema='public' and table_name='aktifitas_fieldtrip_photo' and column_name='aktifitas_fieldtrip_id')
     and not exists (select 1 from information_schema.columns where table_schema='public' and table_name='aktifitas_fieldtrip_photo' and column_name='aktifitas_id') then
    alter table public.aktifitas_fieldtrip_photo rename column aktifitas_fieldtrip_id to aktifitas_id;
  end if;

  if exists (select 1 from information_schema.columns where table_schema='public' and table_name='aktifitas_akhwah_photo' and column_name='aktifitas_akhwah_id')
     and not exists (select 1 from information_schema.columns where table_schema='public' and table_name='aktifitas_akhwah_photo' and column_name='aktifitas_id') then
    alter table public.aktifitas_akhwah_photo rename column aktifitas_akhwah_id to aktifitas_id;
  end if;

  -- Pastikan kolom storage_path & caption ada di tabel photo
  if not exists (select 1 from information_schema.columns where table_schema='public' and table_name='aktifitas_fieldtrip_photo' and column_name='storage_path') then
    alter table public.aktifitas_fieldtrip_photo add column storage_path text;
  end if;
  if not exists (select 1 from information_schema.columns where table_schema='public' and table_name='aktifitas_fieldtrip_photo' and column_name='caption') then
    alter table public.aktifitas_fieldtrip_photo add column caption text;
  end if;

  if not exists (select 1 from information_schema.columns where table_schema='public' and table_name='aktifitas_akhwah_photo' and column_name='storage_path') then
    alter table public.aktifitas_akhwah_photo add column storage_path text;
  end if;
  if not exists (select 1 from information_schema.columns where table_schema='public' and table_name='aktifitas_akhwah_photo' and column_name='caption') then
    alter table public.aktifitas_akhwah_photo add column caption text;
  end if;
end $$;

