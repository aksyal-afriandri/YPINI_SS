-- 2. TABEL: AKTIFITAS FIELD TRIP & FOTO
-- ------------------------------------------------------------------------------
create table if not exists public.aktifitas_fieldtrip (
    id bigint generated by default as identity primary key,
    nama_kegiatan text not null check (char_length(trim(nama_kegiatan)) between 1 and 255),
    tanggal_kegiatan date not null default current_date,
    deskripsi text,
    created_at timestamptz not null default now(),
    updated_at timestamptz not null default now()
);

create table if not exists public.aktifitas_fieldtrip_photo (
    id bigint generated by default as identity primary key,
    aktifitas_id bigint not null references public.aktifitas_fieldtrip (id) on delete cascade,
    url_foto text not null,
    storage_path text,
    caption text,
    created_at timestamptz not null default now(),
    updated_at timestamptz not null default now()
);

