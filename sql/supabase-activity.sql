-- 8. STORAGE BUCKET: activity-photos
-- ------------------------------------------------------------------------------
insert into storage.buckets (id, name, public, file_size_limit, allowed_mime_types)
values (
  'activity-photos',
  'activity-photos',
  true,
  10485760, -- 10 MB per foto
  array['image/jpeg', 'image/png', 'image/webp', 'image/gif']
)
on conflict (id) do update set
  public = true,
  file_size_limit = 10485760,
  allowed_mime_types = array['image/jpeg', 'image/png', 'image/webp', 'image/gif'];

-- Storage Policies
drop policy if exists "activity_photos_public_read" on storage.objects;
create policy "activity_photos_public_read" on storage.objects
  for select using (bucket_id = 'activity-photos');

drop policy if exists "activity_photos_auth_insert" on storage.objects;
create policy "activity_photos_auth_insert" on storage.objects
  for insert to authenticated
  with check (bucket_id = 'activity-photos');

drop policy if exists "activity_photos_auth_update" on storage.objects;
create policy "activity_photos_auth_update" on storage.objects
  for update to authenticated
  using (bucket_id = 'activity-photos')
  with check (bucket_id = 'activity-photos');

drop policy if exists "activity_photos_auth_delete" on storage.objects;
create policy "activity_photos_auth_delete" on storage.objects
  for delete to authenticated
  using (bucket_id = 'activity-photos');

